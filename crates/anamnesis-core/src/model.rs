//! Shared data model. Every crate speaks these types.
//!
//! Changing anything here is a cross-crate change: coordinate before editing.

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};

pub type Timestamp = DateTime<Utc>;

/// Opaque, sortable id (ULID string).
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(transparent)]
pub struct Id(pub String);

impl Id {
    pub fn new() -> Self {
        Id(ulid::Ulid::new().to_string())
    }
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl Default for Id {
    fn default() -> Self {
        Self::new()
    }
}

impl std::fmt::Display for Id {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

/// Who wrote the text. Voice/"thinks like me" metrics only ever use `Owner*`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Origin {
    /// Typed by the user (editor, their own vault, their own site).
    OwnerWritten,
    /// The user's own text spoken and transcribed.
    OwnerSpoken,
    /// The user's highlight or annotation on someone else's text.
    OwnerAnnotation,
    /// Something the user said inside a chat with an assistant.
    OwnerInChat,
    /// Generated by a model.
    AiGenerated,
    /// The user's text edited or rewritten by a model.
    AiEdited,
    /// Someone else's text (articles, PDFs, books, quotes, feeds).
    External,
}

impl Origin {
    pub fn is_owner(self) -> bool {
        matches!(
            self,
            Origin::OwnerWritten | Origin::OwnerSpoken | Origin::OwnerAnnotation | Origin::OwnerInChat
        )
    }
    /// The "speaker" bucket used by the "when you wrote" chart.
    pub fn speaker(self) -> Speaker {
        match self {
            o if o.is_owner() => Speaker::You,
            Origin::AiGenerated | Origin::AiEdited => Speaker::Assistants,
            _ => Speaker::Other,
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Speaker {
    You,
    Assistants,
    Other,
}

/// What an item is ("group by what it is" in the ui).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ItemKind {
    Note,
    Journal,
    Quote,
    Article,
    Pdf,
    Book,
    Chat,
    Clip,
    Feed,
    Skill,
}

/// Per-item / per-source egress rule for cloud models.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum Privacy {
    /// Never sent to a non-local model.
    LocalOnly,
    /// May be sent to the user's chosen model.
    #[default]
    CloudOk,
    /// Ask each time.
    Ask,
}

/// Where an item came from. One row per configured source (a vault, a feed, the editor...).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Source {
    pub id: Id,
    /// Connector id, e.g. "folder", "obsidian", "rss", "pdf", "web", "editor", "chat", "mcp".
    pub connector: String,
    pub name: String,
    /// Connector-specific config (paths, urls...). Never holds secrets.
    pub config: serde_json::Value,
    pub default_origin: Origin,
    pub default_privacy: Privacy,
    /// Opaque incremental-sync cursor owned by the connector.
    pub cursor: Option<String>,
    pub created_at: Timestamp,
}

/// A document as produced by a connector, before it becomes an Item.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Document {
    /// Stable id inside the source (relative path, guid, url). Used for updates/deletes.
    pub external_id: String,
    pub uri: Option<String>,
    pub kind: ItemKind,
    pub title: String,
    /// Plain text or Markdown body.
    pub body: String,
    pub origin: Origin,
    /// When the thing was written (frontmatter date, file mtime, feed pubDate...).
    pub created_at: Option<Timestamp>,
    pub modified_at: Option<Timestamp>,
    pub tags: Vec<String>,
    /// Outgoing references found in the text: [[wikilinks]], markdown links, urls.
    pub refs: Vec<String>,
    /// Anything else (frontmatter, author, feed name). Kept verbatim for provenance.
    pub meta: serde_json::Value,
}

/// A stored item: a note, source, chat, quote... one dot in the brain.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Item {
    pub id: Id,
    pub source_id: Id,
    pub external_id: String,
    pub uri: Option<String>,
    pub kind: ItemKind,
    pub title: String,
    pub body: String,
    pub origin: Origin,
    pub privacy: Privacy,
    /// When it was written.
    pub created_at: Timestamp,
    /// When anamnesis first saw it.
    pub captured_at: Timestamp,
    pub modified_at: Timestamp,
    /// sha256 of the normalised body, hex.
    pub content_hash: String,
    pub tags: Vec<String>,
    pub meta: serde_json::Value,
    pub deleted: bool,
}

/// A retrievable slice of an item with its character span (for citations).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Chunk {
    pub id: Id,
    pub item_id: Id,
    pub ord: u32,
    pub text: String,
    /// Byte offsets into Item.body.
    pub start: usize,
    pub end: usize,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum LinkKind {
    /// [[wikilink]] or markdown link written in the text.
    Written,
    /// Made by hand in the ui / via mcp.
    Manual,
    /// A suggestion the user accepted.
    AcceptedSuggestion,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Link {
    pub from: Id,
    pub to: Id,
    pub kind: LinkKind,
    pub created_at: Timestamp,
}

/// Structured things extracted from text, tracked through a lifecycle.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ThreadKind {
    Decision,
    OpenQuestion,
    Plan,
    Rejection,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ThreadStatus {
    Open,
    Resolved,
    Abandoned,
    Superseded,
}

/// A decision / open question / plan / rejection with provenance.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Thread {
    pub id: Id,
    pub kind: ThreadKind,
    pub status: ThreadStatus,
    /// Short statement in the user's words where possible.
    pub statement: String,
    /// Item the thread was found in, and the verbatim quote that supports it.
    pub item_id: Id,
    pub quote: String,
    /// Item that resolved / superseded it, if any.
    pub resolved_by: Option<Id>,
    pub created_at: Timestamp,
    pub updated_at: Timestamp,
    /// "rule" | "local:<model>" | "<provider>:<model>"
    pub extractor: String,
}

/// A stable cluster ("region of the brain").
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Region {
    pub id: Id,
    /// Lowercase label, e.g. "ethics of attention".
    pub label: String,
    /// Optional anatomical name used by the "anatomy" view, e.g. "angular gyrus".
    pub anatomy: Option<String>,
    pub size: u32,
    pub born_at: Timestamp,
    pub died_at: Option<Timestamp>,
    pub parent_ids: Vec<Id>,
}

/// MONIC-style transitions between clustering runs.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum RegionTransition {
    Birth { region: Id },
    Survive { region: Id },
    Split { from: Id, into: Vec<Id> },
    Merge { from: Vec<Id>, into: Id },
    Death { region: Id },
}

/// Position of an item in the 3D brain, plus its region.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Placement {
    pub item_id: Id,
    pub xyz: [f32; 3],
    pub region_id: Option<Id>,
}

/// Who caused an event.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Actor {
    User,
    /// A connector sync, e.g. "connector:obsidian".
    Connector(String),
    /// A background job inside anamnesis, e.g. "mind:cluster".
    System(String),
    /// An external harness over mcp, e.g. "mcp:claude-code".
    Mcp(String),
    /// A model, e.g. "model:anthropic/claude-haiku-5-5".
    Model(String),
}

/// Everything that changes the brain is an event in an append-only, hash-chained log.
/// The log is the source of truth for evaluation and for replaying growth.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum EventKind {
    SourceAdded { source: Source },
    SourceRemoved { source_id: Id },
    ItemCreated { item: Item },
    ItemUpdated { item: Item },
    ItemDeleted { item_id: Id },
    LinkAdded { link: Link },
    LinkRemoved { from: Id, to: Id },
    /// A link suggestion was computed. `shown=false` means randomly held out (the control arm).
    SuggestionMade { suggestion_id: Id, from: Id, to: Id, score: f32, rank: u32, shown: bool, model: String },
    SuggestionAccepted { suggestion_id: Id },
    SuggestionDismissed { suggestion_id: Id },
    ThreadAdded { thread: Thread },
    ThreadUpdated { thread: Thread },
    RegionsRecomputed { run_id: Id, regions: Vec<Region>, transitions: Vec<RegionTransition> },
    LayoutUpdated { run_id: Id, placements_hash: String, count: u32 },
    /// Resurfacing: `arm` is "algorithm" or "random" (micro-randomised trial).
    ResurfaceShown { resurface_id: Id, item_id: Id, arm: String },
    ResurfaceRated { resurface_id: Id, useful: bool },
    /// A user relevance label for retrieval evaluation (grade 0..=3).
    RetrievalLabeled { query: String, item_id: Id, grade: u8 },
    /// Something left the machine for a model. Never contains the text, only counts.
    Egress { provider: String, model: String, purpose: String, items: Vec<Id>, chars: u64 },
    /// A chat turn (the app's own chats are items too; this records the exchange).
    ChatTurn { chat_id: Id, role: String, item_id: Id, cited: Vec<Id> },
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Event {
    pub seq: u64,
    pub at: Timestamp,
    pub actor: Actor,
    pub kind: EventKind,
    /// hex sha256 of the previous event's hash ‖ this event's canonical json (without hash).
    pub prev_hash: String,
    pub hash: String,
}

/// A search hit with its citation span.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Hit {
    pub item_id: Id,
    pub chunk_id: Option<Id>,
    pub title: String,
    pub snippet: String,
    pub score: f32,
    pub start: usize,
    pub end: usize,
}
